#!/usr/bin/env python3
"""Laptop-keyboard flight controls through the real engine keymap.

Stages fixtures/laptop-keymap-lines.txt ahead of the generated engine defaults
in keymap.cfg (first match wins in Keymap::Read), then drives the real
OrbiterCore session with process-local SDL physical key events. Positive runs
must observe real engine attmode, thruster group and polled-DIK transitions;
the negative control withholds publication and must fail the oracle while
still tearing down cleanly.
"""
import json
from pathlib import Path
import subprocess
import sys
from fixture_staging import stage
from mesh_regression import require
from camera_regression import verify_presentation

LAPTOP_LINES = (Path(__file__).resolve().with_name('fixtures') / 'laptop-keymap-lines.txt').read_text()
OVERRIDDEN = {'IncMainThrust', 'DecMainThrust', 'KillMainRetroThrust', 'OverrideFullMainThrust',
              'OverrideFullRetroThrust', 'IncHoverThrust', 'DecHoverThrust', 'RCSEnable', 'RCSMode',
              'RCSPitchUp', 'RCSPitchDown', 'RCSYawLeft', 'RCSYawRight', 'RCSBankLeft', 'RCSBankRight',
              'RCSUp', 'RCSDown', 'RCSLeft', 'RCSRight', 'RCSForward', 'RCSBack',
              'LPRCSPitchUp', 'LPRCSPitchDown', 'LPRCSYawLeft', 'LPRCSYawRight', 'LPRCSBankLeft', 'LPRCSBankRight',
              'LPRCSUp', 'LPRCSDown', 'LPRCSLeft', 'LPRCSRight', 'LPRCSForward', 'LPRCSBack'}


def seed_laptop_keymap(launch):
    # The engine writes its defaults on first launch; prepend the seed so
    # Keymap::Read (first label match wins) selects the laptop bindings.
    if not (launch / 'keymap.cfg').exists():
        raise SystemExit('FAIL: keymap.cfg was not generated by the staged run tree')
    generated = (launch / 'keymap.cfg').read_text()
    seed_names = {line.split('=')[0].strip() for line in LAPTOP_LINES.splitlines() if line.strip() and '=' in line}
    require(seed_names == OVERRIDDEN, 'laptop seed must cover exactly the keypad-only defaults')
    (launch / 'keymap.cfg').write_text(LAPTOP_LINES + '\n' + generated)
    return launch


def main():
    executable, content, output = [Path(x).resolve() for x in sys.argv[1:4]]
    require(sys.argv[4:] in ([], ['--hidden-present']), 'unknown laptop runner options')
    presentation = sys.argv[4:]
    output.mkdir(parents=True, exist_ok=True)
    launch = stage(content, output, prefix='laptop-')
    seed_laptop_keymap(launch)
    for run in range(3):
        result = subprocess.run([str(executable), 'MetalCamera', '20', '--session-laptop-test'] + presentation,
                                cwd=launch, capture_output=True, text=True, timeout=90)
        log = result.stdout + result.stderr
        (output / f'laptop-{run}.log').write_text(log)
        require(result.returncode == 0, 'laptop session executable failed: ' + log)
        records = [json.loads(line.split('laptop_json=', 1)[1]) for line in log.splitlines() if 'laptop_json=' in line]
        require(len(records) == 16 and [r['frame'] for r in records] == list(range(16)), 'laptop frame count/order')
        for r in records:
            require(r['ok'], 'laptop oracle frame mismatch: ' + json.dumps(r))
        # Independent key-level assertions on the observed attmode trajectory:
        # scenario default 1, Ctrl+/ -> 0, Ctrl+/ -> 1, / -> 2 (translational).
        att = [r['attmode'] for r in records]
        require(att[4] == 1 and att[5] == 0 and att[6] == 0 and att[7] == 1 and att[9] == 2 and att[15] == 2,
                'attmode trajectory does not follow the real SetAttMode/ToggleAttMode semantics: ' + str(att))
        require(records[10]['up'] <= 1e-6 < records[11]['up'],
                'physical arrow did not raise the real RCS level: ' + json.dumps(records[11]))
        require(records[12]['up'] > 1e-6 and records[13]['up'] <= 1e-6,
                'held-release RCS level transition wrong: ' + json.dumps([records[12], records[13]]))
        require(records[13]['main'] <= 1e-9 < records[14]['main'] and records[15]['main'] > 1e-9,
                'Ctrl+digit did not raise the real main throttle: ' + json.dumps(records[14]))
        require(records[15]['polled_keys'] == [0, 0, 0, 0], 'held keys must not survive teardown')
        for marker in ('laptop input verified=1', 'teardown complete; PASS',
                       'create=1 close=1 destroy=1 imgui_init=1 imgui_shutdown=1'):
            require(marker in log, 'missing ' + marker)
        if presentation:
            verify_presentation(log, frames=16)
        print(json.dumps({'run': run, 'attmode': att, 'up_at_10': records[10]['up'], 'main_at_13': records[13]['main']}), flush=True)
    # Negative control: same schedule, publication disabled -> oracle must fail.
    result = subprocess.run([str(executable), 'MetalCamera', '20', '--session-laptop-ignore-test'] + presentation,
                            cwd=launch, capture_output=True, text=True, timeout=90)
    log = result.stdout + result.stderr
    (output / 'laptop-ignored.log').write_text(log)
    require(result.returncode != 0 and 'laptop input verified=0' in log and
            'teardown complete; FAIL' in log, 'laptop negative control not rejected: ' + log)
    print('PASS: 3 hidden laptop-key sessions through the real keymap; negative control rejected')


if __name__ == '__main__':
    main()
